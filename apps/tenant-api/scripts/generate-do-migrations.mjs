#!/usr/bin/env node
/**
 * Generates workers/migrations.generated.ts from packages/tenant-db/drizzle SQL files.
 * Run before `wrangler deploy` so esbuild does not need a .sql loader.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = dirname(fileURLToPath(import.meta.url))
const drizzleDir = join(dir, '../../../packages/tenant-db/drizzle')
const journal = JSON.parse(
	readFileSync(join(drizzleDir, 'meta/_journal.json'), 'utf8'),
)

const migrations = Object.fromEntries(
	journal.entries.map((entry) => [
		entry.tag,
		readFileSync(join(drizzleDir, `${entry.tag}.sql`), 'utf8'),
	]),
)

const output = `// Generated by scripts/generate-do-migrations.mjs — do not edit.
import journal from '../../../packages/tenant-db/drizzle/meta/_journal.json'

const migrations: Record<string, string> = ${JSON.stringify(migrations, null, '\t')}

export const durableSqliteMigrations = {
	journal,
	migrations,
} as const
`

writeFileSync(join(dir, '../workers/migrations.generated.ts'), output)
console.log('Wrote workers/migrations.generated.ts')
